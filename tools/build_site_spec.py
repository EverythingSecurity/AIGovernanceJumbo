"""Generate site/grc-spec.js from src/aicontrols/grc_spec.json so the browser and Python share one spec.

Run from the repository root:  python tools/build_site_spec.py        (writes the file)
                               python tools/build_site_spec.py --check (exit 1 if it is out of date)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "aicontrols" / "grc_spec.json"
OUT = ROOT / "site" / "grc-spec.js"


def render() -> str:
    spec = json.loads(SRC.read_text(encoding="utf-8"))
    body = json.dumps(spec, indent=2, ensure_ascii=False)
    return ("// SPDX-License-Identifier: Apache-2.0\n"
            "// Generated by tools/build_site_spec.py from src/aicontrols/grc_spec.json. Do not edit by hand.\n"
            "(function (root) {\n  \"use strict\";\n"
            f"  const spec = {body};\n"
            "  root.AIC = root.AIC || {};\n  root.AIC.grcSpec = spec;\n"
            "  if (typeof module !== \"undefined\" && module.exports) module.exports = spec;\n"
            "})(typeof globalThis !== \"undefined\" ? globalThis : this);\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.is_file() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
