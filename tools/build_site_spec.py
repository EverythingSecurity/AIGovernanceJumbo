"""Generate the browser copies of the layer specs so the browser and Python share one source:

  src/aicontrols/grc_spec.json         -> site/grc-spec.js         (AIC.grcSpec)
  src/aicontrols/engagement_spec.json  -> site/engagement-spec.js  (AIC.engagementSpec)

Run from the repository root:  python tools/build_site_spec.py        (writes the files)
                               python tools/build_site_spec.py --check (exit 1 if any is out of date)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPECS = [("grc_spec.json", "grc-spec.js", "grcSpec"), ("engagement_spec.json", "engagement-spec.js", "engagementSpec")]


def render(src: Path, out_name: str, name: str) -> str:
    spec = json.loads(src.read_text(encoding="utf-8"))
    body = json.dumps(spec, indent=2, ensure_ascii=False)
    return ("// SPDX-License-Identifier: Apache-2.0\n"
            f"// Generated by tools/build_site_spec.py from src/aicontrols/{src.name}. Do not edit by hand.\n"
            "(function (root) {\n  \"use strict\";\n"
            f"  const spec = {body};\n"
            f"  root.AIC = root.AIC || {{}};\n  root.AIC.{name} = spec;\n"
            "  if (typeof module !== \"undefined\" && module.exports) module.exports = spec;\n"
            "})(typeof globalThis !== \"undefined\" ? globalThis : this);\n")


if __name__ == "__main__":
    stale = []
    for src_name, out_name, name in SPECS:
        src, out = ROOT / "src" / "aicontrols" / src_name, ROOT / "site" / out_name
        text = render(src, out_name, name)
        if "--check" in sys.argv:
            if not (out.is_file() and out.read_text(encoding="utf-8") == text):
                stale.append(out_name)
        else:
            out.write_text(text, encoding="utf-8")
            print(f"wrote {out.relative_to(ROOT)}")
    if "--check" in sys.argv:
        if stale:
            print("stale: " + ", ".join(stale), file=sys.stderr)
        sys.exit(1 if stale else 0)
